        let initialIdleRequests = initial.int("idleRequests")

        Thread.sleep(forTimeInterval: 1)
        XCTAssertEqual(
            state(in: app).int("aDry"),
            initialDry,
            "Healthy playback reported renderer starvation before the injection"
        )

