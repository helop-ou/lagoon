                && $0.double("audioLead") < 0.25
        }
        XCTAssertGreaterThan(
            dry.double("time"),
            heldAt + 0.5,
            "Withholding audio unexpectedly stopped the video clock"
        )
        XCTAssertEqual(dry.int("deliveryHeld"), 0)

