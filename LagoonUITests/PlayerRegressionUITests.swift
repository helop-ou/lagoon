    /// Pins the audio-buffering mode (HEL-123): withheld audio stops the
    /// clock after the confirmation delay, is counted as an audio stall,
    /// and playback resumes once the renderer has its lead back.
    func testAudioStarvationBuffersWhenTheModeIsOn() throws {
        let app = launchPlayer(
            title: "audio-starvation-regression",
            extraArguments: [
                "-debug.regressionFindPlayable", "YES",
                "-debug.regressionRequireAudio", "YES",
                "-debug.simulateAudioStarvation", "YES",
                "-debug.starvationInjectionDelaySeconds", "8",
                // On this stream the renderer holds roughly two to three
                // seconds of audio, so the floor is crossed around 2.5 s
                // and the one-second confirmation lands near 3.5 s. A
                // seven-second hold leaves a confirmed stall of about
                // 3.5 s, inside the five-second reprime rule with margin,
                // so the no-reprime assertion below is expected to run
                // rather than be skipped.
                "-debug.starvationInjectionDurationSeconds", "7",
                "-debug.bufferOnAudioStarvation", "YES",
                "-playback.autoplayMode", "off",
            ]
        )
        try requireRegressionFixture(in: app)
        let initial = waitForState(in: app, timeout: 60) {
            $0.int("ready") == 1
                && $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
                && $0.int("audioBuffers") == 1
        }
        let initialStalls = initial.int("stalls")
        let initialAudioStalls = initial.int("audioStalls")
        let initialDry = initial.int("aDry")
        let initialReprimes = initial.int("reprimes")

        _ = waitForState(in: app, timeout: 15) { $0.int("audioHeld") == 1 }
        let buffering = waitForState(in: app, timeout: 9) { $0.int("buffering") == 1 }
        let stallBegan = Date()
        XCTAssertEqual(buffering.int("aDry"), initialDry + 1)

        _ = waitForState(in: app, timeout: 12) { $0.int("audioHeld") == 0 }
        let stallReleased = Date()
        let recovered = waitForState(in: app, timeout: 20) {
            $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
                && $0.double("time") > buffering.double("time") + 0.5
        }
        // Report every counter on a failure: which of them moved says which
        // recovery path the engine took.
        continueAfterFailure = true
        XCTAssertEqual(recovered.int("stalls"), initialStalls + 1, recovered.raw)
        XCTAssertEqual(recovered.int("audioStalls"), initialAudioStalls + 1, recovered.raw)
        XCTAssertEqual(recovered.int("aDry"), initialDry + 1, recovered.raw)
        XCTAssertLessThanOrEqual(recovered.int("videoMax"), recovered.int("videoHard"), recovered.raw)

        let confirmedStallSeconds = stallReleased.timeIntervalSince(stallBegan)
        print("AudioBufferingProbe confirmedStall=\(confirmedStallSeconds) \(recovered.raw)")
        if confirmedStallSeconds < 4 {
            XCTAssertEqual(
                recovered.int("reprimes"),
                initialReprimes,
                "A stall of \(confirmedStallSeconds)s should have refilled in place rather than falling back to a seek: \(recovered.raw)"
            )
        }
        // Otherwise, a confirmed stall at or beyond the five-second rule is
        // allowed to take the seek fallback, and this test does not pin
        // which side of the rule a given path lands on.
    }

    /// Pins the existing stall recovery path: a demux outage longer than the
    /// video cushion enters buffering, then playback resumes afterwards
    /// within the video hard limit. The seek fallback is asserted absent
    /// only when the confirmed stall was clearly shorter than the
    /// five-second rule. Not evidence about HEL-124.
    func testBoundedDeliveryOutageRecoversThroughStallWithoutReprime() throws {
        let app = launchPlayer(
            title: "delivery-stall-regression",
            extraArguments: [
                "-debug.regressionFindPlayable", "YES",
                "-debug.regressionRequireAudio", "YES",
                "-debug.simulateDeliveryStall", "YES",
                "-debug.starvationInjectionDelaySeconds", "8",
                // The compressed path coasts on up to 120 queued frames
                // (about 5 s at 24 fps) plus a 1 s confirmation before
                // buffering shows, so the hold has to outlast that. A
                // decoded path (30 frames) stalls much sooner and may cross
                // the 5 s reprime rule, which is why the reprime assertion
                // below is conditional.
                "-debug.starvationInjectionDurationSeconds", "8",
                "-playback.autoplayMode", "off",
            ]
        )
        try requireRegressionFixture(in: app)
        let initial = waitForState(in: app, timeout: 60) {
            $0.int("ready") == 1
                && $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
                && $0.int("videoHard") > 0
        }
        let initialReprimes = initial.int("reprimes")
        let held = waitForState(in: app, timeout: 15) { $0.int("deliveryHeld") == 1 }
        _ = waitForState(in: app, timeout: 9) { $0.int("buffering") == 1 }
        let stallBegan = Date()

        _ = waitForState(in: app, timeout: 12) { $0.int("deliveryHeld") == 0 }
        let stallReleased = Date()
        let recovered = waitForState(in: app, timeout: 20) {
            $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
                && $0.double("time") > held.double("time") + 0.5
        }
        let confirmedStallSeconds = stallReleased.timeIntervalSince(stallBegan)
        if confirmedStallSeconds < 4 {
            XCTAssertEqual(
                recovered.int("reprimes"),
                initialReprimes,
                "A stall of \(confirmedStallSeconds)s should have refilled in place rather than falling back to a seek"
            )
        }
        // Otherwise, a confirmed stall at or beyond the five-second rule is
        // allowed to take the seek fallback, and this test does not pin
        // which side of the rule a given path lands on.
        XCTAssertLessThanOrEqual(
            recovered.int("videoMax"),
            recovered.int("videoHard"),
            "Recovery exceeded the active video-memory bound"
        )
        XCTAssertEqual(recovered.int("audioHeld"), 0)
    }

    /// Pins the HEL-124 fix: each HLS fragment's `mdat` is one contiguous
    /// video block followed by one contiguous audio block, so a demuxer
    /// that stops reading once the decoded video queue hits its hard limit
    /// only reaches a fragment's audio after that fragment's last video
    /// frame — starving the renderer once per fragment on the HLS rungs
    /// (13 `aDry` episodes in 70 s on the remux rung, per docs/playback.md).
    /// The fix parks read-ahead compressed video in an intake queue so the
    /// demux loop keeps reading into the audio block instead of parking on
    /// the decoded limit. Forces the cheap remux rung via the injected
    /// first-delivery failure — the same rung the original repro
    /// sawtoothed on — then holds it to both bounds across 40 s of real
    /// playback: the decoded backlog stays inside its hard limit and the
    /// intake queue stays inside `DemuxBackpressurePolicy.videoIntakeHardLimit`,
    /// with no additional dry episode, stall, or reprime.
    func testForcedRemuxKeepsAudioFedWithinTheIntakeBound() throws {
        // Mirrors `DemuxBackpressurePolicy.videoIntakeHardLimit`. The UI
        // test target cannot import the app module, so the bound is
        // pinned here as a literal instead — keep the two in sync.
        let videoIntakeHardLimit = 600

        let app = launchPlayer(
            title: "hls-remux-intake-regression",
            extraArguments: [
                "-debug.regressionFindPlayable", "YES",
                "-debug.regressionRequireAudio", "YES",
                "-debug.regressionFailFirstDelivery", "delivery",
                "-playback.autoplayMode", "off",
                // An intro auto-skip must not seek mid-run and confuse the
                // rung/readiness sequence this test watches for below.
                "-playback.skipMode", "button",
            ]
        )
        try requireRegressionFixture(in: app)
        _ = waitForState(in: app, timeout: 60) {
            $0.int("ready") == 1
                && $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
        }

        // The injected failure fires 4 s after this engine starts and
        // steps the delivery down to the remux rung. `method` alone can't
        // tell that apart from an ordinary transcode — Jellyfin's
        // `PlayMethod` reads `Transcode` for both, and on some simulators
        // the first engine is already a transcode (a 4K HEVC title the
        // simulator can only play that way), so `method` never even
        // changes. `rung` is the app's own delivery-ladder state, so
        // `remux` is unambiguous regardless of what the first engine
        // used. The remux rung can then take 10-20 s to come back up,
        // hence the generous timeout.
        let fallenBack = waitForState(in: app, timeout: 60) {
            $0.string("rung") == "remux"
                && $0.int("ready") == 1
                && $0.int("buffering") == 0
                && $0.double("audioLead") > 0.25
        }

        // The switch itself may have counted a dry episode; that is not
        // what this test is pinning, so the baseline is read after the
        // switch rather than assumed to be zero.
        let baselineDry = fallenBack.int("aDry")
        let baselineStalls = fallenBack.int("stalls")
        let baselineReprimes = fallenBack.int("reprimes")

        var observedHealthyLead = false
        for _ in 0..<40 {
            Thread.sleep(forTimeInterval: 1)
            let sample = state(in: app)
            XCTAssertEqual(
                sample.int("buffering"),
                0,
                "Remux playback buffered while the demux read past the decoded video limit: \(sample.raw)"
            )
            XCTAssertLessThanOrEqual(
                sample.int("videoMax"),
                sample.int("videoHard"),
                "Decoded video backlog exceeded its hard limit during remux playback: \(sample.raw)"
            )
            XCTAssertLessThanOrEqual(
                sample.int("videoIntakeMax"),
                videoIntakeHardLimit,
                "Intake queue exceeded DemuxBackpressurePolicy.videoIntakeHardLimit: \(sample.raw)"
            )
            if sample.double("audioLead") > 0.25 { observedHealthyLead = true }
        }

        let final = state(in: app)
        XCTAssertTrue(
            observedHealthyLead,
            "Audio lead never rose back above the floor during 40 s of remux playback: \(final.raw)"
        )
        XCTAssertEqual(
            final.int("aDry"),
            baselineDry,
            "Remux playback starved the audio renderer during 40 s of interleaved fMP4 fragments: \(final.raw)"
        )
        XCTAssertEqual(
            final.int("stalls"),
            baselineStalls,
            "Remux playback stalled during the 40 s intake-bound window: \(final.raw)"
        )
        XCTAssertEqual(
            final.int("reprimes"),
            baselineReprimes,
            "Remux playback reprimed during the 40 s intake-bound window: \(final.raw)"
        )
    }

