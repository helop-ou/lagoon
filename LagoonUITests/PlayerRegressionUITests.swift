    /// Distinguishes a player failure from a server that simply lacks the
    /// specialized media fixture. The public Jellyfin demo currently has no
    /// subtitle, multi-audio, chapter, or intro-segment item; those journeys
    /// run when a fixture server is supplied through LAGOON_REGRESSION_*.
    private func requireRegressionFixture(
        in app: XCUIApplication,
        timeout: TimeInterval = 25
    ) throws {
        // A cold simulator launch has two independent network handshakes:
        // authenticate the ephemeral regression account, then resolve the
        // requested media. A transient failure in the first handshake leaves
        // the app on Sign In, where neither player probe exists. Retry that
        // launch once instead of reporting a player failure for work that
        // never reached the player. Explicit fixture/API results remain
        // terminal so a real regression is never hidden by the retry.
        for launchAttempt in 0..<2 {
            let deadline = Date().addingTimeInterval(timeout)
            let resolution = app.descendants(matching: .any)["player.regression.resolution"]
            repeat {
                if app.descendants(matching: .any)["player.regression.state"].exists { return }
                if resolution.exists {
                    let value = resolution.value as? String ?? ""
                    if value.hasPrefix("missing:") {
                        throw XCTSkip(
                            "Fixture server " + String(value.dropFirst("missing:".count))
                        )
                    }
                    if value.hasPrefix("error:") {
                        throw RegressionFixtureError(message: String(value.dropFirst("error:".count)))
                    }
                }
                Thread.sleep(forTimeInterval: 0.2)
            } while Date() < deadline

            if launchAttempt == 0 {
                app.terminate()
                Thread.sleep(forTimeInterval: 0.5)
                app.launch()
            }
        }
        throw RegressionFixtureError(message: "did not resolve a player fixture before timeout")
    }

    /// Guards the HLS cases against silently testing something else.
    ///
    /// Jellyfin, not the client, chooses the delivery method, and it chooses
    /// it from the device profile. `-debug.simulatorTranscode` swaps in
    /// `DeviceProfile.simulatorRegression`, which only withdraws HEVC and
    /// Dolby Vision — it still advertises H.264/VC1 direct play, so a server
    /// whose items are H.264 answers `DirectPlay` and no HLS playlist is ever
    /// opened. That is what the public demo does: every item there is H.264,
    /// so these two cases asserted `Transcode`, failed on the first
    /// assertion, and never reached the segment-boundary window they exist
    /// for (HEL-144 / audit A18).
    ///
    /// A missing fixture is not a player regression, so the public-demo lane
    /// skips with an explicit reason. A supplied fixture server is expected to
    /// carry content that must transcode, so `DirectPlay` there is a genuine
    /// failure and stays one.
    private func requireNegotiatedTranscode(
        _ state: RegressionState,
        file: StaticString = #filePath,
        line: UInt = #line
    ) throws {
        let method = state.string("method")
        guard method != "Transcode" else { return }
        guard let server = ProcessInfo.processInfo.environment["LAGOON_REGRESSION_SERVER"] else {
            throw XCTSkip("""
                Fixture server required: playback negotiated \(method), so this run \
                never opened an HLS playlist and cannot test segment boundaries. \
                The simulator regression profile still permits H.264 direct play \
                and every public-demo item is H.264. Supply a server whose content \
                must transcode through LAGOON_REGRESSION_SERVER / \
                LAGOON_REGRESSION_USER / LAGOON_REGRESSION_PASS.
                """)
        }
        XCTFail(
            """
            Fixture server \(server) negotiated \(method) instead of Transcode, \
            so the HLS transport was not exercised. State: \(state.raw)
            """,
            file: file,
            line: line
        )
        throw RegressionFixtureError(message: "fixture server did not negotiate a transcode")
    }

    private func waitForFrameLossResult(
        in app: XCUIApplication,
        timeout: TimeInterval
    ) throws -> FrameLossRegressionResult {
        let deadline = Date().addingTimeInterval(timeout)
        let probe = app.descendants(matching: .any)["player.regression.frameLoss"]
        repeat {
            if probe.exists,
               let value = probe.value as? String,
               let result = FrameLossRegressionResult(value) {
                return result
            }
            Thread.sleep(forTimeInterval: 1)
        } while Date() < deadline
        throw RegressionFixtureError(message: "frame-loss window did not finish before timeout")
    }

    @discardableResult
    private func waitForState(
        in app: XCUIApplication,
        timeout: TimeInterval,
        predicate: (RegressionState) -> Bool
    ) -> RegressionState {
        let deadline = Date().addingTimeInterval(timeout)
        var latest = RegressionState("")
        repeat {
            latest = state(in: app)
            if predicate(latest) { return latest }
            Thread.sleep(forTimeInterval: 0.2)
        } while Date() < deadline
        XCTFail("Timed out waiting for player state. Latest: \(latest.raw)")
        return latest
    }

    private func state(in app: XCUIApplication) -> RegressionState {
        let element = app.descendants(matching: .any)["player.regression.state"]
        guard element.exists else { return RegressionState("") }
        return RegressionState(element.value as? String ?? "")
    }

    @discardableResult
    private func waitForLifecycle(
        in app: XCUIApplication,
        timeout: TimeInterval,
        predicate: (RegressionState) -> Bool
    ) -> RegressionState {
        let deadline = Date().addingTimeInterval(timeout)
        var latest = RegressionState("")
        repeat {
            let element = app.descendants(matching: .any)["app.lifecycle.state"]
            if element.exists {
                latest = RegressionState(element.value as? String ?? "")
                if predicate(latest) { return latest }
            }
            Thread.sleep(forTimeInterval: 0.2)
        } while Date() < deadline
        XCTFail("Timed out waiting for playback lifecycle. Latest: \(latest.raw)")
        return latest
    }

